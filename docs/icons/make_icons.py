#!/usr/bin/env python3
# Converts icons.txt (16x16 ASCII art) into application/include/user_interface/uiIcons.h
import os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'icons.txt')).read().splitlines()
icons, name, rows = [], None, []
for line in src + ['@END']:
    if line.startswith('#') or not line.strip():
        continue
    if line.startswith('@'):
        if name:
            rows = (rows + ['.' * 16] * 16)[:16]
            icons.append((name, rows))
        name, rows = line[1:].strip(), []
    else:
        rows.append(line.strip().ljust(16, '.')[:16])
out = ['/* Generated by docs/icons/make_icons.py from docs/icons/icons.txt - do not edit. */',
       '#ifndef _OPENGD77_UI_ICONS_H_', '#define _OPENGD77_UI_ICONS_H_', '#include <stdint.h>', '',
       'typedef enum', '{']
out += [f'\tUI_ICON_{n},' for n, _ in icons] + ['\tUI_ICON_MAX', '} uiIcon_t;', '',
        '// 16 rows of 16 pixels, bit 15 = leftmost', 'static const uint16_t uiIcons[UI_ICON_MAX][16] =', '{']
for n, rows in icons:
    vals = ', '.join('0x%04X' % int(''.join('1' if c == '#' else '0' for c in r), 2) for r in rows)
    out.append(f'\t{{ {vals} }}, // {n}')
out += ['};', '', '#endif', '']
dst = os.path.join(here, '..', '..', 'MDUV380_firmware', 'application', 'include', 'user_interface', 'uiIcons.h')
open(dst, 'w').write('\n'.join(out))
print(len(icons), 'icons ->', os.path.relpath(dst))
